#!/usr/bin/env bash
# Acceptance test for the linc-sim3d HAL component.
#
# Runs under halrun, so it needs a host where rtapi can start (a real LinuxCNC
# box, not a container with a read-only /dev/shm). It loads the component,
# drives the input pins with setp (a fake position source: no joints, no
# motion), sweeps X across the modelled workpiece, and asserts the probe
# contact and collision outputs.
#
# Checks, one PASS/FAIL line each:
#   1  clear      probe-out is 0 at the start of the sweep
#   2  contact    probe-out turns 1 somewhere in the sweep
#   3  exact      that contact lands on LINC_SIM3D_TEST_X_EXPECT (when set)
#   4  inside     probe-out is still 1 one step deeper
#   5  retract    probe-out returns to 0 at the start position
#   6  tip        tip-x reports the commanded X at the contact point
#   7  collision  collision stays 0 for the whole probe move
#
# Environment:
#   LINC_SIM3D_TEST_CONFIG  config file, absolute or relative to the repo root
#                           (default configs/sim3d.toml)
#   LINC_SIM3D_TEST_Y       Y of the sweep (default 0)
#   LINC_SIM3D_TEST_Z       Z of the sweep (default 0)
#   LINC_SIM3D_TEST_SWEEP   X sweep as start:end:step (default -40:40:1)
#   LINC_SIM3D_TEST_SETTLE  seconds to wait after each setp (default 0.08)
#   LINC_SIM3D_TEST_TOOL    tool number to load (default 99, the probe in
#                           configs/sim3d.toml); probe-out only moves while the
#                           probe is in the spindle
#   LINC_SIM3D_TEST_X_EXPECT
#                           expected contact X; set it when the fixture
#                           geometry is known, so check 3 runs
#
# The fixture must contain one workpiece the probe reaches while X sweeps
# through it at the given Y/Z. The component samples its own input pins every
# config.hal.sample_ms, hence the settle time between setp and getp.

set -uo pipefail

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
repo_root=$(cd -- "$script_dir/.." && pwd)

failures=0
checks=0

pass() {
    checks=$((checks + 1))
    printf 'PASS  %s\n' "$*"
}

fail() {
    checks=$((checks + 1))
    failures=$((failures + 1))
    printf 'FAIL  %s\n' "$*"
}

skip() {
    printf 'SKIP  %s\n' "$*"
    exit 0
}

binary=""
for profile in release debug; do
    candidate="$repo_root/target/$profile/linc-sim3d"
    if [[ -x "$candidate" ]]; then
        binary="$candidate"
        break
    fi
done
if [[ -z "$binary" ]]; then
    fail "no linc-sim3d binary in target/release or target/debug; run: cargo build --release -p linc-sim3d"
    exit 1
fi

config="${LINC_SIM3D_TEST_CONFIG:-configs/sim3d.toml}"
[[ "$config" == /* ]] || config="$repo_root/$config"
if [[ ! -f "$config" ]]; then
    fail "config not found: $config"
    exit 1
fi

for tool in halrun halcmd; do
    command -v "$tool" >/dev/null 2>&1 || skip "$tool is not installed, so rtapi cannot run here"
done

y="${LINC_SIM3D_TEST_Y:-0}"
z="${LINC_SIM3D_TEST_Z:-0}"
tool="${LINC_SIM3D_TEST_TOOL:-99}"
sweep="${LINC_SIM3D_TEST_SWEEP:--40:40:1}"
settle="${LINC_SIM3D_TEST_SETTLE:-0.08}"

IFS=: read -r x_start x_end x_step <<<"$sweep"
for value in "$y" "$z" "$tool" "$x_start" "$x_end" "$x_step"; do
    if [[ ! $value =~ ^-?[0-9]+(\.[0-9]+)?$ ]]; then
        fail "not a number: '$value' (check the LINC_SIM3D_TEST_* settings)"
        exit 1
    fi
done
if ! awk -v step="$x_step" 'BEGIN { exit !(step > 0) }'; then
    fail "the sweep step must be positive, got '$x_step'"
    exit 1
fi
for value in "$binary" "$config"; do
    if [[ $value == *" "* ]]; then
        fail "loadusr cannot take a path with spaces: $value"
        exit 1
    fi
done

tmpdir=$(mktemp -d "${TMPDIR:-/tmp}/linc-sim3d-hal-test.XXXXXX") || {
    fail "cannot create a temporary directory"
    exit 1
}
trap 'rm -rf "$tmpdir"' EXIT
hal_file="$tmpdir/sim3d-test.hal"
log="$tmpdir/halrun.log"

xs=$(awk -v s="$x_start" -v e="$x_end" -v d="$x_step" \
    'BEGIN { for (x = s; x <= e + d / 1000; x += d) printf "%.4f\n", x }')
if [[ -z "$xs" ]]; then
    fail "the sweep produced no points: $sweep"
    exit 1
fi
mapfile -t x_values <<<"$xs"
x_count=${#x_values[@]}

# The HAL script: one component, a net on each reported output, then the sweep.
# loadusr -w sleep leaves the engine thread time to sample after every setp;
# halrun tears the component down with SIGTERM, which --hal handles.
{
    echo "# generated by scripts/sim3d-hal-test.sh"
    echo "loadusr -Wn linc-sim3d $binary --hal --config $config"
    echo "net sim3d-probe linc-sim3d.probe-out"
    echo "net sim3d-collision linc-sim3d.collision"
    echo "setp linc-sim3d.pos-y $y"
    echo "setp linc-sim3d.pos-z $z"
    echo "setp linc-sim3d.tool-number $tool"
    echo "setp linc-sim3d.tool-offset 0"
    for x in "${x_values[@]}"; do
        echo "setp linc-sim3d.pos-x $x"
        echo "loadusr -w sleep $settle"
        echo "getp linc-sim3d.probe-out"
        echo "getp linc-sim3d.collision"
        echo "getp linc-sim3d.tip-x"
    done
    echo "setp linc-sim3d.pos-x $x_start"
    echo "loadusr -w sleep $settle"
    echo "getp linc-sim3d.probe-out"
} >"$hal_file"

if ! halrun -f "$hal_file" >"$log" 2>&1; then
    fail "halrun failed; log tail:"
    tail -n 15 "$log" | sed 's/^/      /'
    printf 'FAILED %d of %d checks\n' "$failures" "$checks"
    exit 1
fi

# Collect the numeric answers in order. halrun prints one value per getp, and a
# line may be bare ("1") or prefixed with the pin name ("pin = 1"), so strip
# the pin name and keep only pure numbers.
mapfile -t values < <(awk '
    {
        line = $0
        sub(/\r$/, "", line)
        sub(/^[[:space:]]*linc-sim3d\.[A-Za-z0-9_.-]+[[:space:]]*[=:]?[[:space:]]*/, "", line)
        sub(/[[:space:]]+$/, "", line)
        if (line ~ /^[-+]?[0-9]+(\.[0-9]+)?([eE][-+]?[0-9]+)?$/) print line
    }
' "$log")

expected_values=$((x_count * 3 + 1))
if [[ ${#values[@]} -ne $expected_values ]]; then
    fail "expected $expected_values values from halrun, got ${#values[@]}; log tail:"
    tail -n 15 "$log" | sed 's/^/      /'
    printf 'FAILED %d of %d checks\n' "$failures" "$checks"
    exit 1
fi

is_zero() { awk -v v="$1" 'BEGIN { exit !(v + 0 == 0) }'; }

close_to() {
    awk -v a="$1" -v b="$2" -v tol="$3" 'BEGIN {
        d = a - b
        if (d < 0) d = -d
        exit !(d <= tol)
    }'
}

contact_index=-1
contact_x=""
collision_hits=0
collision_first=""
for i in "${!x_values[@]}"; do
    probe=${values[$((i * 3))]}
    collision=${values[$((i * 3 + 1))]}
    if ! is_zero "$collision"; then
        collision_hits=$((collision_hits + 1))
        [[ -n "$collision_first" ]] || collision_first="x=${x_values[$i]}"
    fi
    if [[ $probe != 0 && $contact_index -lt 0 ]]; then
        contact_index=$i
        contact_x=${x_values[$i]}
    fi
done
retract=${values[$((x_count * 3))]}

if is_zero "${values[0]}"; then
    pass "1 clear: probe-out is 0 at x=${x_values[0]}"
else
    fail "1 clear: probe-out is already 1 at x=${x_values[0]} (start the sweep clear of the workpiece)"
fi

if [[ $contact_index -ge 0 ]]; then
    pass "2 contact: probe-out went 0->1 at x=$contact_x"
else
    fail "2 contact: probe-out never went high sweeping $sweep at y=$y z=$z with T$tool loaded (does the config hold a workpiece there, and is T$tool its probe?)"
fi

if [[ -n "${LINC_SIM3D_TEST_X_EXPECT:-}" ]]; then
    if [[ -z "$contact_x" ]]; then
        fail "3 exact: no contact to compare with LINC_SIM3D_TEST_X_EXPECT=${LINC_SIM3D_TEST_X_EXPECT}"
    elif awk -v expect="$LINC_SIM3D_TEST_X_EXPECT" -v seen="$contact_x" -v step="$x_step" \
        'BEGIN { exit !(expect <= seen + 0.0001 && expect > seen - step - 0.0001) }'; then
        # The sample grid decides where contact is first seen, so the expected
        # coordinate may be up to one step beyond the reported one.
        pass "3 exact: contact at $contact_x matches LINC_SIM3D_TEST_X_EXPECT=${LINC_SIM3D_TEST_X_EXPECT}"
    else
        fail "3 exact: contact at $contact_x, expected ${LINC_SIM3D_TEST_X_EXPECT} (one step is $x_step)"
    fi
fi

if [[ $contact_index -ge 0 && $((contact_index + 1)) -lt $x_count ]]; then
    if close_to "${values[$(((contact_index + 1) * 3))]}" 1 0; then
        pass "4 inside: probe-out stays 1 at x=${x_values[$((contact_index + 1))]}"
    else
        fail "4 inside: probe-out dropped again one step past contact at x=${x_values[$((contact_index + 1))]}"
    fi
fi

if is_zero "$retract"; then
    pass "5 retract: probe-out is 0 again at x=$x_start"
else
    fail "5 retract: probe-out is still $retract at x=$x_start"
fi

if [[ $contact_index -ge 0 ]]; then
    if close_to "${values[$((contact_index * 3 + 2))]}" "$contact_x" 0.001; then
        pass "6 tip: tip-x reports the commanded x=$contact_x"
    else
        fail "6 tip: tip-x is ${values[$((contact_index * 3 + 2))]}, expected $contact_x"
    fi
fi

if [[ $collision_hits -eq 0 ]]; then
    pass "7 collision: stayed 0 across $x_count sweep points"
else
    fail "7 collision: went high at $collision_first ($collision_hits of $x_count points)"
fi

printf '\n'
if [[ $failures -gt 0 ]]; then
    printf 'FAILED %d of %d checks\n' "$failures" "$checks"
    exit 1
fi
printf 'PASSED all %d checks\n' "$checks"
exit 0
